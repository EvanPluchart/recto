fn lang() -> Lang {
    static LANG: OnceLock<Lang> = OnceLock::new();
    *LANG.get_or_init(|| {
        // An explicit setting first, then the system language.
        // On Windows, LANG and LC_ALL come from Unix-like shells (Git Bash), not from the system.
        let keys: &[&str] = if cfg!(windows) { &["RECTO_LANG"] } else { &["RECTO_LANG", "LC_ALL", "LANG"] };
        let value = keys
            .iter()
            .find_map(|key| std::env::var(key).ok().filter(|v| !v.is_empty()))
            .or_else(sys_locale::get_locale);
        match value {
            Some(v) if v.to_ascii_lowercase().starts_with("fr") => Lang::Fr,
            _ => Lang::En,
        }
    })
}

pub fn t(source: &'static str) -> &'static str {
    match lang() {
        Lang::En => source,
        Lang::Fr => FR.iter().find(|(en, _)| *en == source).map_or(source, |(_, fr)| fr),
    }
}
